#!/usr/bin/env node
// Prints the SQL that loads supabase/seed/knowledge/*.md into knowledge_base.
// One card = "## <question>", then "<!-- audience: x | category: y | step_code: z -->",
// then the answer until the next "## ". One upsert per file on (source_file,
// category, question), as the same question can appear in two categories:
// unchanged cards are left as they are, and the embedding (computed in L1-27)
// is reset only when the answer changed. Cards removed from a file are deleted.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../supabase/seed/knowledge/", import.meta.url));
const lit = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);

const statements = [];
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort()) {
  const lines = readFileSync(join(dir, file), "utf8").split("\n");
  const cards = [];
  let current = null;
  for (const line of lines) {
    if (line.startsWith("## ")) {
      current = { question: line.slice(3).trim(), meta: null, body: [] };
      cards.push(current);
    } else if (current && current.meta === null && line.trim().startsWith("<!--")) {
      const meta = {};
      for (const part of line.replace(/<!--|-->/g, "").split("|")) {
        const [key, ...rest] = part.split(":");
        if (key && rest.length) meta[key.trim()] = rest.join(":").trim();
      }
      current.meta = meta;
    } else if (current) {
      current.body.push(line);
    }
  }
  if (cards.length === 0) {
    statements.push(`delete from public.knowledge_base where source_file = ${lit(file)};`);
    continue;
  }
  const rows = cards.map((card) => {
    if (!card.meta?.audience || !card.meta?.category) {
      throw new Error(`${file}: card without metadata: ${card.question}`);
    }
    const answer = card.body.join("\n").trim();
    const values = [card.meta.audience, card.meta.category, card.meta.step_code || null];
    return `(${[...values, card.question, answer, file].map(lit).join(", ")})`;
  });
  statements.push(
    `insert into public.knowledge_base (audience, category, step_code, question, answer, source_file) values\n` +
      `${rows.join(",\n")}\n` +
      `on conflict (source_file, category, question) do update set audience = excluded.audience, ` +
      `step_code = excluded.step_code, answer = excluded.answer, ` +
      `embedding = case when public.knowledge_base.answer is distinct from excluded.answer then null ` +
      `else public.knowledge_base.embedding end, updated_at = now() ` +
      `where (public.knowledge_base.audience, public.knowledge_base.step_code, public.knowledge_base.answer) ` +
      `is distinct from (excluded.audience, excluded.step_code, excluded.answer);`,
    `delete from public.knowledge_base where source_file = ${lit(file)} and (category, question) not in (` +
      cards.map((c) => `(${lit(c.meta.category)}, ${lit(c.question)})`).join(", ") +
      `);`,
  );
}
process.stdout.write(`-- Generated by scripts/seed-knowledge.mjs\n${statements.join("\n")}\n`);
